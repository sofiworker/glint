#!/usr/bin/env python3
"""Generate native action SVGs from prototype/icons.js. Use --check in validation."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = (ROOT / "prototype/icons.js").read_text(encoding="utf-8")
    paths = json.loads(re.search(r"const paths = (\{.*?\});", source, re.S).group(1))
    outputs = {}
    for name, path in paths.items():
        if not re.fullmatch(r"[a-z_]+", name) or not re.fullmatch(r"[MmLlHhVvCcSsQqTtAaZz0-9., +\-]+", path):
            raise ValueError(f"Invalid SVG icon geometry: {name}")
        outputs[ROOT / f"crates/glint-ui/ui/icons/{name}.svg"] = (
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
            'stroke="#202b42" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">'
            f'<path d="{path}"/></svg>\n'
        )
    outputs[ROOT / "crates/glint-ui/ui/components/icons.slint"] = (
        '// SPDX-License-Identifier: GPL-3.0-only\n'
        '// Generated by tools/sync_icons.py from prototype/icons.js.\n'
        'export global GlintIcons {\n' + ''.join(
            f'    out property <image> {name.replace("_", "-")}: @image-url("../icons/{name}.svg");\n'
            for name in paths
        ) + '}\n'
    )
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Icon assets need regeneration: " + ", ".join(stale))
    print(f'{len(paths)} action icons: {"in sync" if args.check else "generated"}')


if __name__ == "__main__":
    main()
