#!/usr/bin/env python3
"""Generate prototype and native icons from the pinned local Lucide SVG subset."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/icons/lucide"
SVG_NS = "{http://www.w3.org/2000/svg}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((SOURCE / "manifest.json").read_text(encoding="utf-8"))
    for filename, expected in manifest["sha256"].items():
        if not re.fullmatch(r"[a-z0-9-]+\.svg|LICENSE\.txt", filename):
            raise ValueError(f"Invalid Lucide source filename: {filename}")
        if hashlib.sha256((SOURCE / filename).read_bytes()).hexdigest() != expected:
            raise ValueError(f"Lucide source checksum mismatch: {filename}")
    icons = {}
    outputs = {}
    for name, upstream in manifest["icons"].items():
        if not re.fullmatch(r"[a-z_]+", name) or upstream + ".svg" not in manifest["sha256"]:
            raise ValueError(f"Invalid Lucide icon mapping: {name}")
        source = (SOURCE / f"{upstream}.svg").read_text(encoding="utf-8")
        svg = ET.fromstring(source)
        if svg.tag != SVG_NS + "svg" or svg.attrib["viewBox"] != "0 0 24 24":
            raise ValueError(f"Invalid Lucide SVG: {upstream}")
        for node in svg.iter():
            if node.tag.removeprefix(SVG_NS) not in {"svg", "path", "rect", "circle", "ellipse", "line", "polyline", "polygon"}:
                raise ValueError(f"Unsupported SVG element: {upstream}")
            for key, value in node.attrib.items():
                if key.lower().startswith("on") or key in {"href", "style"} or "url(" in value:
                    raise ValueError(f"Unsafe SVG attribute: {upstream}")
        body = re.search(r"<svg\b[^>]*>(.*?)</svg>", source, re.S).group(1)
        icons[name] = re.sub(r">\s+<", "><", re.sub(r"\s+", " ", body)).strip()
    # Generate the interaction specification first, then the embedded native assets.
    aliases = {upstream: name for name, upstream in manifest["icons"].items()}
    aliases.update(manifest["aliases"])
    if any(target not in icons for target in aliases.values()):
        raise ValueError("Unknown icon alias target")
    notice = (
        f'Lucide lucide-static v{manifest["version"]}; Copyright (c) 2026 Lucide Icons and Contributors. '
        'Feather-derived icons: Copyright (c) 2013-present Cole Bemis. '
        'ISC/MIT terms: assets/icons/lucide/LICENSE.txt.'
    )
    outputs[ROOT / "prototype/icons.js"] = (
        '/* SPDX-License-Identifier: GPL-3.0-only AND ISC AND MIT\n'
        ' * Generated by tools/sync_icons.py. Do not edit.\n'
        f' * {notice}\n */\n'
        "(() => {\n  'use strict';\n  const icons = " + json.dumps(icons, indent=2) + ';\n'
        '  const aliases = ' + json.dumps(aliases, separators=(',', ':')) + ';\n'
        '  const svg=(name,size=18)=>`<svg class="glint-icon" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${icons[aliases[name]||name]||icons.more}</svg>`;\n'
        "  const render=(root=document)=>root.querySelectorAll('[data-glint-icon]').forEach(node=>{node.outerHTML=svg(node.dataset.glintIcon);});\n"
        '  globalThis.GlintIcons=Object.freeze({svg,render});\n})();\n'
    )
    for name, body in icons.items():
        outputs[ROOT / f"crates/glint-ui/ui/icons/{name}.svg"] = (
            f'<!-- SPDX-License-Identifier: ISC AND MIT; {notice} -->\n'
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
            'stroke="#202b42" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
            f'{body}</svg>\n'
        )
    outputs[ROOT / "crates/glint-ui/ui/components/icons.slint"] = (
        '// SPDX-License-Identifier: GPL-3.0-only\n'
        '// Generated by tools/sync_icons.py from assets/icons/lucide/manifest.json.\n'
        'export global GlintIcons {\n' + ''.join(
            f'    out property <image> {name.replace("_", "-")}: @image-url("../icons/{name}.svg");\n'
            for name in icons
        ) + '}\n'
    )
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Icon assets need regeneration: " + ", ".join(stale))
    print(f'{len(icons)} Lucide icons: {"in sync" if args.check else "generated"}')


if __name__ == "__main__":
    main()
